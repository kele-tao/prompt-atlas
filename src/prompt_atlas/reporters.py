"""Markdown and JSON reporters.

The JSON reporter is a stable, documented schema (see docs/json-schema.md):
consumers write CI policies against it, so keys are never renamed casually.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from typing import Any

from .differ import DiffResult
from .model import AXES, LintResult


def results_to_json(results: Iterable[LintResult], version: str) -> str:
    """Serialise every lint result as one deterministic JSON document."""
    payload = {
        "tool": "prompt-atlas",
        "version": version,
        "prompts": [result.as_dict() for result in results],
    }
    return json.dumps(payload, indent=2, sort_keys=False, ensure_ascii=False)


def diff_to_json(result: DiffResult, version: str) -> str:
    """Serialise a diff result."""
    payload = {"tool": "prompt-atlas", "version": version, "diff": result.as_dict()}
    return json.dumps(payload, indent=2, ensure_ascii=False)


def _escape_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def results_to_markdown(results: list[LintResult], version: str) -> str:
    """Render a Markdown report suitable for a PR comment."""
    total = len(results)
    average = round(sum(r.score.total for r in results) / total, 1) if total else 0.0
    failing = [r for r in results if r.issues]
    lines: list[str] = [
        "# prompt-atlas report",
        "",
        f"Prompts analysed: **{total}** | mean score: **{average}** | "
        f"with findings: **{len(failing)}**",
        "",
        "## Scores",
        "",
        "| Prompt | Score | Grade | Tokens | Findings |",
        "| --- | ---: | :---: | ---: | ---: |",
    ]
    for result in results:
        name = result.document.meta.get("name") or result.path
        lines.append(
            f"| `{_escape_cell(str(name))}` | {result.score.total:.1f} | {result.score.grade} "
            f"| {result.document.token_count} | {len(result.issues)} |"
        )
    lines.extend(["", "## Axis averages", "", "| Axis | Average |", "| --- | ---: |"])
    for axis in AXES:
        values = [r.score.axes[axis] for r in results]
        mean = round(sum(values) / len(values), 1) if values else 0.0
        lines.append(f"| {axis} | {mean} |")
    lines.extend(["", "## Findings", ""])
    any_findings = False
    for result in results:
        if not result.issues:
            continue
        any_findings = True
        name = result.document.meta.get("name") or result.path
        lines.append(f"### {name}")
        lines.append("")
        lines.append("| Rule | Severity | Line | Message | Fix |")
        lines.append("| --- | --- | ---: | --- | --- |")
        for issue in result.issues:
            lines.append(
                f"| `{issue.rule}` | {issue.severity} | {issue.line} "
                f"| {_escape_cell(issue.message)} | {_escape_cell(issue.hint)} |"
            )
        lines.append("")
    if not any_findings:
        lines.append("No findings. Every prompt passed every rule.")
    lines.extend(["", f"Generated by prompt-atlas {version}."])
    return "\n".join(lines)


def summary_row(result: LintResult) -> dict[str, Any]:
    """Compact row used by the HTML report tables."""
    return {
        "name": str(result.document.meta.get("name") or result.path),
        "path": result.path,
        "score": result.score.total,
        "grade": result.score.grade,
        "tokens": result.document.token_count,
        "errors": len(result.errors),
        "warnings": len(result.warnings),
        "infos": len([i for i in result.issues if i.severity == "info"]),
        "findings": len(result.issues),
    }
