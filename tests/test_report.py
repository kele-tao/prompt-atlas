"""Reporters and HTML output: structure, escaping, offline safety."""

from __future__ import annotations

import json

from prompt_atlas import lint_text, render_html, render_json, render_markdown
from prompt_atlas.htmlreport import score_color, sparkline
from prompt_atlas.reporters import summary_row


def two_results():
    return [
        lint_text("# Task\nHandle the thing, some of it.", "a.md"),
        lint_text("You are a helper.\nYou must answer in JSON.\nExample: {}", "b.md"),
    ]


def test_markdown_report_has_score_table():
    body = render_markdown(two_results())
    assert "| Prompt | Score | Grade |" in body
    assert "## Axis averages" in body
    assert "Generated by prompt-atlas" in body


def test_markdown_escapes_pipes_in_messages():
    result = lint_text("# Task\nHandle the thing | pipe, some of them.")
    row = summary_row(result)
    row["name"] = "a|b"
    from prompt_atlas.reporters import _escape_cell

    assert _escape_cell("a|b") == "a\\|b"
    assert _escape_cell("line\nbreak") == "line break"
    assert "| Prompt |" in render_markdown([result])


def test_json_report_schema():
    payload = json.loads(render_json(two_results()))
    assert payload["tool"] == "prompt-atlas"
    assert payload["prompts"][0]["path"] == "a.md"
    finding = payload["prompts"][0]["findings"][0]
    assert set(finding) == {"rule", "severity", "line", "message", "hint", "axis", "deduction"}


def test_html_report_is_self_contained():
    body = render_html(two_results())
    assert body.startswith("<!doctype html>")
    assert "<style>" in body
    assert "http" not in body.lower().replace("http-equiv", "")
    assert "<script" not in body


def test_html_report_escapes_prompt_names():
    result = lint_text("---\nname: <script>alert(1)</script>\n---\n# Task\nHandle it.", "x.md")
    body = render_html([result])
    assert "<script>alert(1)</script>" not in body
    assert "&lt;script&gt;alert(1)&lt;/script&gt;" in body


def test_html_report_handles_empty_input():
    body = render_html([])
    assert "0 prompts" in body
    assert "Mean score" in body


def test_sparkline_returns_svg():
    svg = sparkline([10, 50, 90])
    assert svg.startswith("<svg")
    assert svg.count("polyline") == 1
    assert sparkline([]) == ""


def test_score_color_bands():
    assert score_color(99) == "#22c55e"
    assert score_color(72) == "#eab308"
    assert score_color(55) == "#f97316"
    assert score_color(10) == "#ef4444"


def test_summary_row_counts():
    result = lint_text("# Task\nHandle the thing, some of it, etc.")
    row = summary_row(result)
    assert row["findings"] == len(result.issues)
    assert row["warnings"] == len(result.warnings)
    assert row["errors"] == len(result.errors)
